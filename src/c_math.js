// ---------- sun (NOAA-style approximation, accurate to a fraction of a degree) ----------
function sunPos(ms, lat, lon) {
  const n = ms / 86400000 + 2440587.5 - 2451545.0;
  const L = (280.460 + 0.9856474 * n) % 360;
  const g = ((357.528 + 0.9856003 * n) % 360) * DEG;
  const lam = (L + 1.915 * Math.sin(g) + 0.020 * Math.sin(2 * g)) * DEG;
  const eps = (23.439 - 0.0000004 * n) * DEG;
  const ra = Math.atan2(Math.cos(eps) * Math.sin(lam), Math.cos(lam));
  const dec = Math.asin(Math.sin(eps) * Math.sin(lam));
  const gmst = ((18.697374558 + 24.06570982441908 * n) % 24 + 24) % 24;
  const H = (gmst * 15 + lon) * DEG - ra;
  const phi = lat * DEG;
  const el = Math.asin(Math.sin(phi) * Math.sin(dec) + Math.cos(phi) * Math.cos(dec) * Math.cos(H));
  const azS = Math.atan2(Math.sin(H), Math.cos(H) * Math.sin(phi) - Math.tan(dec) * Math.cos(phi));
  return { az: ((azS / DEG + 180) % 360 + 360) % 360, el: el / DEG };
}
function lastSundayUTC(y, m) { const d = new Date(Date.UTC(y, m + 1, 0)); return Date.UTC(y, m, d.getUTCDate() - d.getUTCDay(), 1); }
function madridOffsetH(y, ms) { return (ms >= lastSundayUTC(y, 2) && ms < lastSundayUTC(y, 9)) ? 2 : 1; }
function localToUTC(y, mo, d, minutes) {
  const guess = Date.UTC(y, mo, d, 12);
  return Date.UTC(y, mo, d, 0, minutes) - madridOffsetH(y, guess) * 3600000;
}
function dayInfo(y, mo, d) {
  let rise = null, set = null;
  for (let t = 0; t <= 1440; t += 5) {
    const e = sunPos(localToUTC(y, mo, d, t), SITE.lat, SITE.lon).el;
    if (e > -0.6) { if (rise === null) rise = t; set = t; }
  }
  return { rise: rise ?? 360, set: set ?? 1080 };
}
